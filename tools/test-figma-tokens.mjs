// node tools/test-figma-tokens.mjs — the design file's palette is a copy of
// :root, and this is the only thing that notices when the copy stops matching.
//
// The office's colours live in one place, `:root` in web/style.css, and the
// Figma collection `System` mirrors them under `palette/*`. Nothing connected
// the two: an agent could raise --muted for contrast and the mockups would keep
// the old value for months, or a designer could pick a new brown in Figma and
// the office would never hear about it. Drift like that is found by eye, on a
// frame somebody happens to look at closely, which is to say months late.
//
// Why a snapshot and not a live read. Figma's Variables REST API answers 403
// for this project's token — the `file_variables:read` scope is Enterprise-only
// — so there is no way to ask the file at test time. `tools/figma-tokens.json`
// is exported from the file through the Figma MCP instead, and this stand
// compares that export with the CSS. So the failure it reports is always the
// same one: the two sides disagree, and somebody has to say which is right.
//
// The snapshot is regenerated by an agent, never edited by hand — hand-editing
// it would make the check pass while the file it describes still disagrees,
// which is worse than no check.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const CSS = 'web/style.css';
const SNAP = 'tools/figma-tokens.json';

let bad = 0;
const ok = (name, cond, got) => {
  if (cond) console.log('ok    |', name);
  else { bad += 1; console.log('FAIL  |', name, got === undefined ? '' : '→ ' + JSON.stringify(got)); }
};

// ------------------------------------------------------------------ the sides
const css = fs.readFileSync(path.join(ROOT, CSS), 'utf8');
const snap = JSON.parse(fs.readFileSync(path.join(ROOT, SNAP), 'utf8'));

// Comments are blanked rather than cut: a hex quoted in a comment is
// documentation, not a declaration, and blanking keeps the line numbers.
const blank = (src) => src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '));

// Short hex is expanded and the case is dropped, so #FFF and #ffffff are the
// same colour to this check — CSS treats them as one and so must we.
const norm = (hex) => {
  let h = hex.trim().toLowerCase().replace('#', '');
  if (h.length === 3) h = h.split('').map((c) => c + c).join('');
  return '#' + h;
};

const rootBlock = blank(css).match(/:root\{([\s\S]*?)\n\}/);
ok('the :root block is in place', !!rootBlock);
if (!rootBlock) process.exit(1);

const cssVars = new Map();
for (const m of rootBlock[1].matchAll(/--([\w-]+)\s*:\s*(#[0-9a-fA-F]{3,8})\s*;/g)) {
  cssVars.set(m[1], norm(m[2]));
}
ok(`in :root ${cssVars.size} colors`, cssVars.size > 20, cssVars.size);

const palette = new Map(Object.entries(snap.palette).map(([k, v]) => [k, norm(v)]));
ok(`in a snapshot of ${palette.size} primitives`, palette.size > 20, palette.size);

// --------------------------------------------------------------- the compare
// Three ways the two sides can disagree, and they are different bugs: a colour
// the office has and the mockups do not is a token nobody can paint with; the
// other way round is a token pointing at a colour that no longer exists; and a
// name present on both sides with different values is the one that ships a
// frame in the wrong brown.
const onlyCss = [...cssVars.keys()].filter((n) => !palette.has(n));
const onlyFigma = [...palette.keys()].filter((n) => !cssVars.has(n));
const differ = [...cssVars.entries()]
  .filter(([n, v]) => palette.has(n) && palette.get(n) !== v)
  .map(([n, v]) => ({ name: n, css: v, figma: palette.get(n) }));

if (onlyCss.length) {
  bad += 1;
  console.log(`FAIL  | ${CSS} has a color missing from the layouts; regenerate the snapshot`);
  for (const n of onlyCss.slice(0, 10)) console.log(`      | --${n} = ${cssVars.get(n)}`);
  if (onlyCss.length > 10) console.log(`      | …and ${onlyCss.length - 10} more`);
} else ok('every color from :root is in the layouts', true);

if (onlyFigma.length) {
  bad += 1;
  console.log(`FAIL  | the layouts have a primitive missing from ${CSS}`);
  for (const n of onlyFigma.slice(0, 10)) console.log(`      | palette/${n} = ${palette.get(n)}`);
  if (onlyFigma.length > 10) console.log(`      | …and ${onlyFigma.length - 10} more`);
} else ok('every layout primitive is in :root', true);

if (differ.length) {
  bad += 1;
  console.log('FAIL  | a color has one name but two values');
  for (const d of differ) console.log(`      | --${d.name}: ${CSS} ${d.css} · layouts ${d.figma}`);
} else ok('values are the same until the last digit', true);

// ------------------------------------------------------- semantics point home
// A semantic token is an alias onto a primitive. An alias onto a name that is
// not in the palette means the export caught the collection mid-rename, and
// every frame painted from that token is painted from nothing in particular.
const dangling = Object.entries(snap.semantic).filter(([, target]) => !palette.has(target));
if (dangling.length) {
  bad += 1;
  console.log('FAIL  | a semantic token points to a missing primitive');
  for (const [name, target] of dangling.slice(0, 10)) console.log(`      | ${name} → palette/${target}`);
} else ok(`${Object.keys(snap.semantic).length} semantic tokens refer to live primitives`, true);

// The snapshot says which collection and mode it came from. Without it a stale
// export from another file would pass every check above and mean nothing.
ok('the picture names its collection', typeof snap.collection === 'string' && snap.collection.length > 0, snap.collection);
ok('the picture states the upload date', /^\d{4}-\d{2}-\d{2}$/.test(snap.exported || ''), snap.exported);

console.log(bad ? `\nFAILED: ${bad}` : '\nall green');
process.exit(bad ? 1 : 0);
