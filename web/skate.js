// Скейт. Коридоры длинные, и бег по ним быстро надоедает: на своих двоих от
// лифта до дальней комнаты идти секунд двадцать.
//
// Отличие скейта от «бежать быстрее» — накат. Скорость не появляется и не
// исчезает вместе с клавишей: её набирают толчками и теряют трением, поэтому
// на скейте есть инерция, а у бега её нет. Это же и единственная опасность:
// накат по стене выглядит как застревание, поэтому скорость по оси гасится в
// тот момент, когда движение по ней упёрлось (см. glide в main.js).
//
// Всё в пикселях за кадр при 60 к/с — те же единицы, в которых написан бег
// (1.35 шагом, 2.6 бегом), чтобы числа можно было сравнивать глазами.

export const ACCEL = 0.14;        // разгон с места до крейсерской ~ за 0.6 с
export const CRUISE = 3.4;        // быстрее бега, но не настолько, чтобы промахиваться мимо дверей
export const CRUISE_PUSH = 4.6;   // SHIFT — оттолкнуться сильнее
export const DRAG = 0.020;        // трение под нагрузкой
export const COAST = 0.045;       // накат без клавиш: ~1.5 с до полной остановки
export const STOP = 0.06;         // ниже этого — ноль, иначе игрок «плывёт» вечно

// Чистая функция: вектор скорости, ввод и длительность кадра — на выходе новая
// скорость. Ради неё модуль и отделён от main.js: физику видно тестом, а
// картинку всё равно приходится смотреть глазами.
export function skateStep({ vx = 0, vy = 0 } = {}, { x = 0, y = 0, push = false } = {}, dt = 1) {
  const cap = push ? CRUISE_PUSH : CRUISE;
  const pushing = x !== 0 || y !== 0;

  vx += x * ACCEL * dt;
  vy += y * ACCEL * dt;

  // Трение множителем, а не вычитанием: вычитание на большом dt (вкладка была
  // в фоне, кадр длиной в три обычных) уводит скорость в минус, и игрок
  // уезжает назад.
  const k = Math.max(0, 1 - (pushing ? DRAG : COAST) * dt);
  vx *= k; vy *= k;

  // Ограничение по длине вектора, а не по каждой оси отдельно: иначе по
  // диагонали скейт едет в 1.41 раза быстрее, чем прямо.
  const mag = Math.hypot(vx, vy);
  if (mag > cap) { vx = (vx / mag) * cap; vy = (vy / mag) * cap; }

  if (!x && Math.abs(vx) < STOP) vx = 0;
  if (!y && Math.abs(vy) < STOP) vy = 0;
  return { vx, vy };
}

export const rolling = ({ vx = 0, vy = 0 }) => Math.hypot(vx, vy) > STOP;

// ------------------------------------------------------------------- олли
// Прыжок с доски. Те же единицы, что и у горизонтальной скорости: пиксели за
// кадр при 60 к/с, чтобы высоту можно было сравнить с длиной шага глазами.
// Высшая точка — 18.2 пикселя, три четверти роста человека. Принято так
// 4 сентября 2026; вариант «свести к 14» (толчок 2.15) отклонён на кадре:
// https://www.figma.com/design/izt4d17qotvyIv7r6BJdSY/AI-Valey?node-id=850-2
export const OLLIE_POP = 2.4;   // 18.2 пикселя в высшей точке
export const GRAVITY = 0.17;    // ~0.5 с в воздухе: дольше читается как полёт

// Чистая функция, как и skateStep: высота, вертикальная скорость и длина кадра
// на входе — новые на выходе. landed поднимается ровно в тот кадр, когда
// коснулись земли, чтобы звук и пыль сыграли один раз, а не каждый кадр.
export function ollieStep({ z = 0, vz = 0 } = {}, dt = 1) {
  if (z <= 0 && vz <= 0) return { z: 0, vz: 0, landed: false };
  const nz = z + vz * dt;
  if (nz <= 0) return { z: 0, vz: 0, landed: true };
  return { z: nz, vz: vz - GRAVITY * dt, landed: false };
}

// Оттолкнуться можно только с земли и только стоя на доске: иначе олли в
// воздухе превращается в бесконечный подъём.
export const canOllie = ({ skate = false, z = 0 } = {}) => !!skate && z <= 0;

// Доска под ногами. Рисуется до человека, потому что он на ней стоит; нос
// загнут по направлению взгляда, чтобы разворот читался без анимации.
export function drawSkateboard(ctx, x, y, dir = 1, moving = false, t = 0, lift = 0) {
  const p = (px, py, w, h, c) => { ctx.fillStyle = c; ctx.fillRect(Math.round(px), Math.round(py), w, h); };
  const d = dir || 1;
  // колёса чуть подпрыгивают на ходу — один пиксель, но без него доска мертвая
  const jig = moving && Math.floor(t / 90) % 2 ? 1 : 0;

  // Тень остаётся на полу и сжимается с высотой — без этого прыжок читается
  // как «доску нарисовали выше», а не как отрыв.
  const k = Math.max(0.35, 1 - lift / 26);
  ctx.fillStyle = `rgba(0,0,0,${0.22 * k})`;
  ctx.beginPath(); ctx.ellipse(x, y + 4, 9 * k, 2 * k, 0, 0, Math.PI * 2); ctx.fill();
  y -= lift;

  p(x - 6, y + 2 + jig, 2, 2, '#e2cfa8');            // колёса
  p(x + 4, y + 2 + jig, 2, 2, '#e2cfa8');
  p(x - 8, y, 16, 2, '#4a3324');                     // дека
  p(x - 8, y, 16, 1, '#6b4a2e');
  p(x + d * 7, y - 1, 2, 2, '#6b4a2e');              // нос
  p(x - d * 8, y - 1, 1, 2, '#4a3324');              // и киктейл сзади
}
