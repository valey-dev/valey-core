// Лицо — это данные плюс их шаг. Вызывающий передаёт лицо, а не ширину: иначе
// шаг и таблица разъезжаются при первой же правке.
export const SMALL = { FONT, W: GLYPH_W, ADVANCE };
export const WIDE = { FONT: FONT_WIDE, W: 5, ADVANCE: 6 };

// Строчных здесь нет: 3×5 их не вмещает, и всё, что рисуется этим шрифтом,
// приводится к прописным. Имя папки при этом меняет вид — «budget-app» на
// табличке становится «BUDGET-APP», — и это осознанная цена варианта.
// Ё складывается в Е, а Й в И: точки и краткая просятся шестой строкой, а
// шестая строка — это другая высота у каждой таблички в офисе. Цена известна и
// принята вместе с кадром.
export const upper = (str) => String(str).toUpperCase().replace(/Ё/g, 'Е').replace(/Й/g, 'И');

// Кириллицы в шрифте нет, и это не забывчивость: рисовать её пришлось бы
// целиком, а имена проектов почти всегда латиницей. Вызывающий сам решает, что
// делать со строкой, которую здесь не нарисовать, — офис откатывается на
// fillText, потому что мыльное имя лучше отсутствующего.
export const canDraw = (str, face = SMALL) => [...upper(str)].every((c) => c in face.FONT);

// Ширина строки без последнего межбуквенного пробела: ровно столько пикселей
// займёт нарисованное.
export const textWidth = (str, face = SMALL, scale = 1) => Math.max(0, (str.length * face.ADVANCE - 1) * scale);

// Рисует строку от левого верхнего угла первой буквы. Соседние по горизонтали
// пиксели сливаются в один fillRect — на строке из шестнадцати знаков это
// втрое меньше вызовов, а картинка та же.
export function drawText(ctx, str, x, y, color, face = SMALL, scale = 1) {
  const s = upper(str);
  const { FONT: table, W, ADVANCE: step } = face;
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const g = table[s[i]];
    if (!g) continue;
    for (let row = 0; row < GLYPH_H; row++) {
      let run = 0;
      for (let col = 0; col <= W; col++) {
        const on = col < W && g[row][col] === '#';
        if (on) { run++; continue; }
        if (run) {
          ctx.fillRect((x + (i * step + col - run) * scale) | 0, (y + row * scale) | 0, run * scale, scale);
          run = 0;
        }
      }
    }
  }
}

