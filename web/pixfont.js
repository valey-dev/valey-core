// Пиксельный шрифт 3×5 для самого мелкого текста в офисе — того, что рисуется
// в мировых пикселях и потом растягивается целыми пикселями вместе с холстом.
//
// Зачем он вообще. Холст 400×225, `imageSmoothingEnabled = false`, css
// `image-rendering: pixelated`. Браузерный `fillText` на семи пикселях рисует
// букву серыми полутонами — стойка тоньше пикселя, — а офис потом раздувает
// каждый серый пиксель в квадрат. 29 августа 2026 сняли табличку клавишей F9:
// написано «v0.1.0 · Node», читается «v8.1.8 · Mode». Для строки, которая вся
// про точный номер версии, это не «мыльно», а неверно. Кегль не помогает: с
// шести на семь стало чуть лучше и упёрлось, потому что дело не в размере, а в
// том, что буква не лежит на пиксельной сетке.
//
// Здесь она лежит: каждый знак — маска 3×5, рисуется прямоугольниками, как вся
// остальная мебель офиса. Чистые цвета, при любом увеличении остаётся собой.

