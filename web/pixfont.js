// Строчных здесь нет: 3×5 их не вмещает, и всё, что рисуется этим шрифтом,
// приводится к прописным. Имя папки при этом меняет вид — «budget-app» на
// табличке становится «BUDGET-APP», — и это осознанная цена варианта.
export const upper = (str) => String(str).toUpperCase();

// Кириллицы в шрифте нет, и это не забывчивость: рисовать её пришлось бы
// целиком, а имена проектов почти всегда латиницей. Вызывающий сам решает, что
// делать со строкой, которую здесь не нарисовать, — офис откатывается на
// fillText, потому что мыльное имя лучше отсутствующего.
export const canDraw = (str) => [...upper(str)].every((c) => c in FONT);

// Ширина строки без последнего межбуквенного пробела: ровно столько пикселей
// займёт нарисованное.
export const textWidth = (str) => Math.max(0, str.length * ADVANCE - 1);

// Рисует строку от левого верхнего угла первой буквы. Соседние по горизонтали
// пиксели сливаются в один fillRect — на строке из шестнадцати знаков это
// втрое меньше вызовов, а картинка та же.
export function drawText(ctx, str, x, y, color) {
  const s = upper(str);
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const g = FONT[s[i]];
    if (!g) continue;
    for (let row = 0; row < GLYPH_H; row++) {
      let run = 0;
      for (let col = 0; col <= GLYPH_W; col++) {
        const on = col < GLYPH_W && g[row][col] === '#';
        if (on) { run++; continue; }
        if (run) { ctx.fillRect((x + i * ADVANCE + col - run) | 0, (y + row) | 0, run, 1); run = 0; }
      }
    }
  }
}

